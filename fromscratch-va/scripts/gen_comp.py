#!/usr/bin/env python3
"""Generate the comparator (dynamic NMOS-input StrongARM latch) subcircuit -> schematic/comparator.spice"""
import sys
P = dict(c_x=100.0, c_out=20.0, outn_size=3.23, w_in=8.0, l_in=0.15, w_tail=4.0, w_nn=2.0, w_np=3.0, w_rst=1.5, w_rsti=1.5, lvt=1, finger_max=0)
for a in sys.argv[2:]:
    k, v = a.split('='); P[k] = float(v)
nin = 'sky130_fd_pr__nfet_01v8_lvt' if P['lvt'] else 'sky130_fd_pr__nfet_01v8'
L = []
a = L.append
a("* StrongARM dynamic comparator, NMOS input (generated by gen_comp.py)")
a("* ports: INP INN CLK(eval when high) OUTP OUTN (precharged to VDD, the output on the larger input side falls) VDD VSS")
a(".subckt comparator inp inn clk outp outn vdd vss")
a("xmt tail clk vss vss sky130_fd_pr__nfet_01v8 w=%g l=0.15" % P['w_tail'])
a("xm1 x inp tail vss %s w=%g l=%g" % (nin, P['w_in'], P['l_in']))
a("xm2 y inn tail vss %s w=%g l=%g" % (nin, P['w_in'], P['l_in']))
# cross coupled: outp is on the INP side (drain of m3 -> x)
a("xm3 outp outn x vss sky130_fd_pr__nfet_01v8 w=%g l=0.15" % P['w_nn'])
a("xm4 outn outp y vss sky130_fd_pr__nfet_01v8 w=%g l=0.15" % P['w_nn'])
a("xm5 outp outn vdd vdd sky130_fd_pr__pfet_01v8 w=%g l=0.15" % P['w_np'])
a("xm6 outn outp vdd vdd sky130_fd_pr__pfet_01v8 w=%g l=0.15" % P['w_np'])
a("xm7 outp clk vdd vdd sky130_fd_pr__pfet_01v8 w=%g l=0.15" % P['w_rst'])
a("xm8 outn clk vdd vdd sky130_fd_pr__pfet_01v8 w=%g l=0.15" % P['w_rst'])
a("xm9 x clk vdd vdd sky130_fd_pr__pfet_01v8 w=%g l=0.15" % P['w_rsti'])
a("xm10 y clk vdd vdd sky130_fd_pr__pfet_01v8 w=%g l=0.15" % P['w_rsti'])
if P['c_x'] > 0:
    import math
    wx = round(math.sqrt(P['c_x'] / 2.0), 2)
    a("xcx1 x vss sky130_fd_pr__cap_mim_m3_1 w=%g l=%g" % (wx, wx))
    a("xcx2 y vss sky130_fd_pr__cap_mim_m3_1 w=%g l=%g" % (wx, wx))
if P['c_out'] > 0:
    # explicit output load (MIM, bottom plate to VSS) to lower the input-referred noise: C ~ 2 fF/um^2 + perimeter
    import math
    wc = round(math.sqrt(P['c_out'] / 2.0), 2)
    a("xcl1 outp vss sky130_fd_pr__cap_mim_m3_1 w=%g l=%g" % (wc, wc))
    a("xcl2 outn vss sky130_fd_pr__cap_mim_m3_1 w=%g l=%g" % (P['outn_size'], P['outn_size']))
a(".ends comparator")
if P['finger_max']:
    import re,math
    for i,line in enumerate(L):
        match=re.search(r' w=([0-9.e+-]+) l=',line)
        if match and 'fet_' in line:
            width=float(match[1]);nf=max(1,int(math.ceil(width/P['finger_max']-1e-9)))
            if nf>1:L[i]=line[:match.start(1)]+str(round(width/nf,2))+line[match.end(1):]+' m='+str(nf)
open(sys.argv[1], 'w').write('\n'.join(L) + '\n')
