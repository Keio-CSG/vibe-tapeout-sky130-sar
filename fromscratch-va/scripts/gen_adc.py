#!/usr/bin/env python3
"""Generate the transistor-level SAR ADC netlists (ngspice compatible) in schematic/:
   cdac.spice (bitcell, cdac_side), sar_logic.spice (sky130_fd_sc_hd gates), comparator.spice (gen_comp.py), sar_adc.spice (top)."""
import sys, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
STDLIB = os.path.join(os.environ["PDKPATH"], "libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice")

PAR = dict(
    cu_w=1.24,          # unit MIM w=l (um) -> 4.0 fF
    wn_tg=48.0, wp_tg=96.0,      # MSB sampling TG widths (um); scaled with the bit weight, min below
    wn_d=6.0, wp_d=30.0,        # MSB reference driver widths
    w_top=2.0,                  # top-plate reset PMOS
    reset_buffer=0,             # positive local reset driver; enabled for voltage-stress fix
    antenna_gate=0,             # increase gate area of the two borderline LO nets
    dummy_ring=132,             # 34x34 outer array minus32x32 active units, both terminalsVSS
    layout_fingers=0,           # model the individual drawn fingers in final schematic runs
    dly_B='dlygate4sd1_1', n_B=2, dly_n='dlygate4sd1_1', n_n=2, dly_c='dlygate4sd1_1', n_c=2,
    dly_run='dlygate4sd3_1', n_run=4, dly_1='dlygate4sd1_1', n_1=2, dly_2='dlygate4sd1_1', n_2=2,
    dly_3='dlygate4sd3_1', n_3=5, dly_q='dlygate4sd1_1', n_q=2,
    outdir=HERE,
)
for a in sys.argv[1:]:
    k, v = a.split('=')
    PAR[k] = type(PAR[k])(v) if k in PAR else v

# --- std cell pin orders -------------------------------------------------------------------
_pins = {}
def pins(cell):
    if not _pins:
        for l in open(STDLIB):
            m = re.match(r'\.subckt sky130_fd_sc_hd__(\S+) (.*)', l)
            if m: _pins[m.group(1)] = m.group(2).split()
    return _pins[cell]

L = []
def emit(s): L.append(s)

class Gates:
    def __init__(self, vdd='vddd', vss='vss'):
        self.vdd, self.vss, self.n = vdd, vss, 0
    def g(self, cell, out, **inp):
        """instantiate std cell; inp maps pin->net; out is the output net (pin Y/X/Q)."""
        self.n += 1
        plist = pins(cell)
        conn = []
        for p in plist:
            if p == 'VGND': conn.append(self.vss)
            elif p == 'VNB': conn.append(self.vss)
            elif p in ('VPWR', 'VPB'): conn.append(self.vdd)
            elif p in ('Y', 'X') or (p == 'Q' and p not in inp):
                conn.append(out if isinstance(out, str) else out[p])
            elif p in inp: conn.append(inp[p])
            elif isinstance(out, dict) and p in out: conn.append(out[p])
            else: raise ValueError("pin %s of %s unconnected" % (p, cell))
        emit("xg%d %s sky130_fd_sc_hd__%s" % (self.n, ' '.join(conn), cell))
        return out
    def dly(self, inp, out, cell, n):
        prev = inp
        for i in range(n):
            o = out if i == n-1 else "%s_d%d" % (out, i)
            self.g(cell, o, A=prev)
            prev = o
        return out

def build_logic():
    emit("* SAR control logic, sky130_fd_sc_hd standard cells (generated by gen_adc.py)")
    emit("* Asynchronous self-timed SAR: non-overlapping track/convert phases from CLK, comparator-valid driven bit cycling.")
    emit(".subckt sar_logic clk coP coN trkA_b trkB trkB_b cnv clkc " +
         ' '.join("lo_p%d" % k for k in range(11)) + ' ' + ' '.join("hib_p%d" % k for k in range(10)) + ' ' +
         ' '.join("lo_n%d" % k for k in range(11)) + ' ' + ' '.join("hib_n%d" % k for k in range(10)) + ' ' +
         ' '.join("d%d" % k for k in range(10, -1, -1)) + " dv vddd vss")
    G = Gates()
    # phase generator
    G.g('inv_2', 'clkb', A='clk')
    G.g('nor2_2', 'trkA', A='clkb', B='cnvd')
    G.g('inv_4', 'trkA_b', A='trkA')
    G.dly('trkA', 'trkBi', PAR['dly_B'], PAR['n_B'])
    G.g('buf_16', 'trkB', A='trkBi')
    G.g('inv_16', 'trkB_b', A='trkB')
    G.dly('trkBi', 'trkBd', PAR['dly_n'], PAR['n_n'])
    G.g('nor2_4', 'cnv', A='clk', B='trkBd')
    G.dly('cnv', 'cnvd', PAR['dly_c'], PAR['n_c'])
    G.dly('cnv', 'run', PAR['dly_run'], PAR['n_run'])
    # comparator handshake
    # each dynamic output drives exactly one inverter (state independent load); NOR SR latch holds the decision
    G.g('inv_1', 'coPb', A='coP')
    G.g('inv_1', 'coNb', A='coN')
    G.g('or2_1', 'valid', A='coPb', B='coNb')
    G.g('nor2_1', 'srq', A='coNb', B='srqb')
    G.g('nor2_1', 'srqb', A='coPb', B='srq')
    G.g('buf_4', 'srq_o', A='srq')        # PEX finding: the NOR SR latch must not drive the 11 bit muxes + wire directly (+5 fF on srq made the ADC fail)
    G.dly('valid', 'v1', PAR['dly_1'], PAR['n_1'])
    G.dly('v1', 'v2', PAR['dly_2'], PAR['n_2'])
    G.dly('v2', 'v3', PAR['dly_3'], PAR['n_3'])
    G.g('nand3_1', 'en_n', A='run', B='cnv', C='qb10')
    # inhibit latch (NOR SR latch): set by v1 (decision seen), reset by v3 (DAC settle delay elapsed) or when not converting
    G.g('inv_1', 'cnv_n', A='cnv')
    G.g('nor2_1', 'inhn', A='v1', B='inh')
    G.g('nor3_1', 'inh', A='v3', B='inhn', C='cnv_n')
    G.g('nor3_2', 'clkc', A='v1', B='inh', C='en_n')
    # pointer: thermometer of inverted bits qb_k (= not q_k) in set-flops (async set while not converting); q_k = 1 once decision k has been applied
    emit("xgzero %s sky130_fd_sc_hd__conb_1" % ' '.join({'HI': 'nc_hi', 'LO': 'zero', 'VGND': 'vss', 'VNB': 'vss', 'VPB': 'vddd', 'VPWR': 'vddd'}[p_] for p_ in pins('conb_1')))
    G.g('inv_1', 'one', A='zero')
    for k in range(11):
        d = 'zero' if k == 0 else 'qb%d' % (k-1)
        G.g('dfstp_1', 'qb%d' % k, CLK='v2', D=d, SET_B='cnv')
    for k in range(11):
        if k == 0: de = 'qb0'
        else:
            G.g('and2b_1', 'tok%d' % k, A_N='qb%d' % (k-1), B='qb%d' % k); de = 'tok%d' % k
        G.g('mux2_1', 'bin%d' % k, A0='b%d' % k, A1='srq_o', S=de)
        G.g('dfstp_1', 'b%d' % k, CLK='v1', D='bin%d' % k, SET_B='one')
    # reference drivers
    for k in range(10):
        s_ = '_2' if k <= 3 else '_1'
        G.dly('qb%d' % k, 'qbd%d' % k, PAR['dly_q'], PAR['n_q'])
        G.g('inv_1', 'bb%d' % k, A='b%d' % k)
        G.g('or2_1', 'sbp%d' % k, A='qb%d' % k, B='bb%d' % k)
        G.g('and2' + s_, 'lo_p%d' % k, A='cnv', B='sbp%d' % k)
        G.g('or2' + s_, 'hib_p%d' % k, A='qbd%d' % k, B='bb%d' % k)
        G.g('or2_1', 'sbn%d' % k, A='qb%d' % k, B='b%d' % k)
        G.g('and2' + s_, 'lo_n%d' % k, A='cnv', B='sbn%d' % k)
        G.g('or2' + s_, 'hib_n%d' % k, A='qbd%d' % k, B='b%d' % k)
    G.g('buf_2', 'lo_p10', A='cnv'); G.g('buf_2', 'lo_n10', A='cnv')
    # outputs
    for k in range(11):
        G.g('buf_2', 'd%d' % (10-k), A='b%d' % k)
    G.g('inv_2', 'dv', A='qb10')
    emit(".ends sar_logic")

def fets(prefix, d, g, s_, b, model, w, l=0.15, wmax=40.0):
    """one MOS or several equal parallel devices if w > wmax (the model bins limit the width of one device)"""
    if PAR['layout_fingers']: wmax=5.0
    n = int(-(-w // wmax)); wf = round(w / n, 2 if PAR['layout_fingers'] else 3)
    return ["%s%d %s %s %s %s %s w=%g l=%g" % (prefix, i, d, g, s_, b, model, wf, l) for i in range(n)]

def build_cdac():
    emit("* Capacitive DAC: bit cells (one subckt per binary weight) and one differential half (generated by gen_adc.py)")
    for k in range(11):
        wgt = 512 >> k if k < 10 else 1
        f = wgt/512.0
        wntg = max(1.5, round(PAR['wn_tg']*f, 2)); wptg = max(1.5, round(PAR['wp_tg']*f, 2))
        wnd = max(1.5, round(PAR['wn_d']*f, 2)); wpd = max(1.5, round(PAR['wp_d']*f, 2))
        if PAR['antenna_gate'] and k in (6,7): wnd=max(wnd,1.8)
        if k < 10:
            emit(".subckt bitcell%d top vin vrefp vrefn vdda vss trk trkb lo hib" % k)
        else:
            emit(".subckt bitcell%d top vin vrefn vdda vss trk trkb lo" % k)
        emit("* binary weight %d x Cu (Cu = %g x %g um MIM = 4 fF), TG W = %g/%g, reference drivers N %g%s" % (wgt, PAR['cu_w'], PAR['cu_w'], wntg, wptg, wnd, (' / P %g' % wpd) if k < 10 else ''))
        emit("xc top bot sky130_fd_pr__cap_mim_m3_1 w=%g l=%g m=%d" % (PAR['cu_w'], PAR['cu_w'], wgt))
        for l_ in fets("xtgn", "vin", "trk", "bot", "vss", "sky130_fd_pr__nfet_01v8", wntg): emit(l_)
        for l_ in fets("xtgp", "vin", "trkb", "bot", "vdda", "sky130_fd_pr__pfet_01v8", wptg): emit(l_)
        for l_ in fets("xdn", "bot", "lo", "vrefn", "vss", "sky130_fd_pr__nfet_01v8", wnd): emit(l_)
        if k < 10:
            for l_ in fets("xdp", "bot", "hib", "vrefp", "vdda", "sky130_fd_pr__pfet_01v8", wpd): emit(l_)
        emit(".ends bitcell%d" % k)
    emit(".subckt cdac_side vin top vrefp vrefn vdda vss trk trkb trkA_b " + ' '.join("lo%d" % k for k in range(11)) + ' ' +
         ' '.join("hib%d" % k for k in range(10)))
    import math
    reset_nf = max(1, int(math.ceil(PAR['w_top']/5.0-1e-9)))
    emit("xsw top trkA_b vdda vdda sky130_fd_pr__pfet_01v8 w=%g l=0.15 m=%d" % (round(PAR['w_top']/reset_nf,2),reset_nf))
    if PAR['dummy_ring']:
        emit('xdummy_ring vss vss sky130_fd_pr__cap_mim_m3_1 w=%g l=%g m=%d' % (PAR['cu_w'],PAR['cu_w'],PAR['dummy_ring']))
    for k in range(11):
        if k < 10:
            emit("xb%d top vin vrefp vrefn vdda vss trk trkb lo%d hib%d bitcell%d" % (k, k, k, k))
        else:
            emit("xb%d top vin vrefn vdda vss trk trkb lo%d bitcell%d" % (k, k, k))
    emit(".ends cdac_side")

def build_top():
    if PAR['reset_buffer']:
        emit('.subckt reset_driver track_b reset_gate vdda vss')
        for name,drain,gate,source,model,mult in [('n0','mid','track_b','vss','nfet',1),('p0','mid','track_b','vdda','pfet',2),('n1','reset_gate','mid','vss','nfet',2),('p1','reset_gate','mid','vdda','pfet',4)]:
            emit('x%s %s %s %s %s sky130_fd_pr__%s_01v8 w=4 l=.15 m=%d' % (name,drain,gate,source,source,model,mult))
        emit('.ends reset_driver')
    emit("* Top level: 11-bit SAR ADC (generated by gen_adc.py)")
    emit("* ports: VINP VINN CLK D10..D0 (D10 = MSB) DV VDDA VDDD VSS VREFP VREFN")
    emit(".subckt sar_adc vinp vinn clk " + ' '.join("d%d" % k for k in range(10, -1, -1)) + " dv vdda vddd vss vrefp vrefn")
    emit("xlogic clk coP coN trkA_b trkB trkB_b cnv clkc " +
         ' '.join("lo_p%d" % k for k in range(11)) + ' ' + ' '.join("hib_p%d" % k for k in range(10)) + ' ' +
         ' '.join("lo_n%d" % k for k in range(11)) + ' ' + ' '.join("hib_n%d" % k for k in range(10)) + ' ' +
         ' '.join("d%d" % k for k in range(10, -1, -1)) + " dv vddd vss sar_logic")
    reset_gate = 'reset_gate' if PAR['reset_buffer'] else 'trkA_b'
    if PAR['reset_buffer']: emit('xreset trkA_b reset_gate vdda vss reset_driver')
    for s, vin in (('p', 'vinp'), ('n', 'vinn')):
        emit("xdac_%s %s top_%s vrefp vrefn vdda vss trkB trkB_b %s " % (s, vin, s,reset_gate) +
             ' '.join("lo_%s%d" % (s, k) for k in range(11)) + ' ' + ' '.join("hib_%s%d" % (s, k) for k in range(10)) + " cdac_side")
    # comparator: INP = top_n, INN = top_p  ->  OUTP falls when VINP > VINN  (c=1)
    emit("xcmp top_n top_p clkc coP coN vdda vss comparator")
    emit(".ends sar_adc")

if __name__ == '__main__':
    out = PAR['outdir']; os.makedirs(out, exist_ok=True)
    for name, fn in (('sar_logic', build_logic), ('cdac', build_cdac), ('sar_adc', build_top)):
        L.clear(); fn(); open(os.path.join(out, name + '.spice'), 'w').write('\n'.join(L) + '\n')
    os.system("python3 %s %s%s" % (os.path.join(HERE, 'gen_comp.py'), os.path.join(out, 'comparator.spice'), ' finger_max=5' if PAR['layout_fingers'] else ''))
    print("generated")
