#!/usr/bin/env python3
"""Generate the transistor-level SPICE schematic of the 11-bit SAR ADC (hierarchical) -> schematic/sar_adc.spice
and the flat unit-cap version for LVS -> schematic/sar_adc_lvs.spice (flatten.py).
Top: sar_adc VINP VINN CLK D0..D10 DV VDDA VDDD VSS VREFP
"""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from spicegen import fet
from comp_def import comparator
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.environ.get("SAR_OUT", os.path.join(HERE, "..", "schematic"))
_pf = os.environ.get("SAR_PARAMS", os.path.join(HERE, "params.json"))
P = json.load(open(_pf)) if os.path.exists(_pf) else {}
def prm(k, d): return P.get(k, d)
CU_W = prm("cu_w", 2.0); CU_L = prm("cu_l", 2.0)          # unit MIM cap (um)
COMP = dict(wtail=prm("c_wtail",4), ltail=0.15, win=prm("c_win",5), lin=0.15, wln=prm("c_wln",2), lln=0.15, wlp=prm("c_wlp",4), llp=0.15, wr=prm("c_wr",2), treset=prm("c_treset",0))
SW_WN, SW_WP = prm("sw_wn", 4.0), prm("sw_wp", 8.0)
def scr(cell, name, pins, conn, vp="VDDD"):
    d = dict(conn); d.update(VPWR=vp, VPB=vp, VGND="VSS", VNB="VSS")
    return f"X{name} " + " ".join(d[p] for p in pins) + f" sky130_fd_sc_hd__{cell}"
def sc(cell, name, pins, conn):
    """standard cell instance with VPWR=VDDD, VGND=VSS, VPB=VDDD, VNB=VSS"""
    d = dict(conn); d.update(VPWR="VDDD", VPB="VDDD", VGND="VSS", VNB="VSS")
    return f"X{name} " + " ".join(d[p] for p in pins) + f" sky130_fd_sc_hd__{cell}"
PINS = {
 "dfrtp_1": "CLK D RESET_B VGND VNB VPB VPWR Q".split(), "dfrtn_1": "CLK_N D RESET_B VGND VNB VPB VPWR Q".split(),
 "and3b_1": "A_N B C VGND VNB VPB VPWR X".split(), "nor3_1": "A B C VGND VNB VPB VPWR Y".split(),
 "nor3_2": "A B C VGND VNB VPB VPWR Y".split(),
 "nand2_1": "A B VGND VNB VPB VPWR Y".split(), "or2_1": "A B VGND VNB VPB VPWR X".split(), "inv_1": "A VGND VNB VPB VPWR Y".split(), "inv_2": "A VGND VNB VPB VPWR Y".split(),
 "inv_4": "A VGND VNB VPB VPWR Y".split(), "buf_2": "A VGND VNB VPB VPWR X".split(), "buf_4": "A VGND VNB VPB VPWR X".split(),
 "dlygate4sd1_1": "A VGND VNB VPB VPWR X".split(), "dlygate4sd3_1": "A VGND VNB VPB VPWR X".split(),
 "dlymetal6s2s_1": "A VGND VNB VPB VPWR X".split(), "clkdlybuf4s25_1": "A VGND VNB VPB VPWR X".split(),
 "and2b_1": "A_N B VGND VNB VPB VPWR X".split(),
 "dlclkp_1": "CLK GATE VGND VNB VPB VPWR GCLK".split(),
 "and2_4": "A B VGND VNB VPB VPWR X".split(),
 "clkbuf_16": "A VGND VNB VPB VPWR X".split(), "inv_8": "A VGND VNB VPB VPWR Y".split(), "inv_16": "A VGND VNB VPB VPWR Y".split(), "buf_8": "A VGND VNB VPB VPWR X".split(),
 "clkdlybuf4s50_1": "A VGND VNB VPB VPWR X".split(), "buf_1": "A VGND VNB VPB VPWR X".split(),
}
def cellx(cell, name, **conn):
    return sc(cell, name, PINS[cell], conn)
DRV = {9: ["inv_16"]*4, 8: ["inv_16"]*2, 7: ["inv_16"], 6: ["inv_8"], 5: ["inv_4"], 4: ["inv_2"], 3: ["inv_1"], 2: ["inv_1"], 1: ["inv_1"], 0: ["inv_1"]}
def driver_sizes(k):
    """bit k (2**k units). returns (std inv cell, wp, wn) for the reference-powered output inverter"""
    wp = max(1.2, prm("drv_wp9",24.0) * 2**(k-9)); wn = max(0.65, wp/2.5)
    first = "inv_4" if k >= 8 else ("inv_2" if k >= 6 else "inv_1")
    if prm("drv_pre_scale",1) == 4 and k >= 6: first = "inv_16" if k >= 8 else "inv_8"
    return first, round(wp,3), round(wn,3)
def build(flat_units=False):
    L = []
    L.append("* FromScratch 11-bit SAR ADC, transistor-level schematic (generated by scripts/gen_schematic.py)")
    L.append("* conventions: sky130A, core 1.8 V devices; std cells sky130_fd_sc_hd on VDDD/VSS")
    L.append(comparator(COMP))
    # transmission-gate sampling switch
    # Keep individual model widths <=64um; larger total switches are parallel instances.
    # This avoids exceeding the PDK's model width bins while preserving LVS total W.
    def swfet(name, kind, d, g, src, body, width, length):
        import math
        n=max(1,math.ceil(width/64))
        if prm("sw_fingered",0):
            import re
            n={"n":8,"p":16,"dn":4,"dp":8}[name]
            wf=width/n
            # Shared-diffusion geometry of the actual Magic gencell, averaged
            # over equal-voltage terminals; no interconnect capacitance added.
            spacing=.29 if length>=.35 else .33
            geom=dict(ad=wf*spacing/2,as_=wf*(spacing/2+.29/n),pd=wf+spacing,ps=wf+spacing+2*(wf+.29)/n)
            lines=[]
            for j in range(n):
                line=fet(name+str(j),kind,d,g,src,body,wf,length)
                for key,val in geom.items():
                    key="as" if key=="as_" else key
                    line=re.sub(r"\b"+key+r"=\S+",key+"="+format(val,".7g"),line)
                lines.append(line)
            return lines
        return [fet(name if n==1 else name+str(j),kind,d,g,src,body,width/n,length) for j in range(n)]
    L += [".subckt tgsw a b g gb gpd VDDA VSS" if prm("sw_dummy_p_inv",0) else ".subckt tgsw a b g gb VDDA VSS"]
    L += swfet("n","nl" if prm("sw_lvt",0) else "n","b","g","a","VSS",SW_WN,0.15)
    L += swfet("p","pl" if prm("sw_lvt",0) else "p","b","gb","a","VDDA",SW_WP,0.35 if prm("sw_lvt",0) else 0.15)
    if prm("sw_dummy", 0):
        L += swfet("dn","nl" if prm("sw_dummy_n_match",prm("sw_dummy_match",0)) else "n","b","gb","b","VSS",SW_WN/2*prm("sw_dummy_n_scale",1),0.15)
        L += swfet("dp","pl" if prm("sw_dummy_p_match",prm("sw_dummy_match",0)) else "p","b","gpd" if prm("sw_dummy_p_inv",0) else "g","b","VDDA",SW_WP/2*prm("sw_dummy_p_scale",1),0.35 if prm("sw_dummy_p_match",prm("sw_dummy_match",0)) else 0.15)
    L += [".ends tgsw"]
    # reference-powered inverter (DAC bottom-plate driver, 2nd stage) parameterised by widths

    L.append(".subckt sar_adc VINP VINN CLK D0 D1 D2 D3 D4 D5 D6 D7 D8 D9 D10 DV VDDA VDDD VSS VREFP")
    # --- sampling and comparator
    pclk=" dummy_ptrk" if prm("sw_dummy_p_inv",0) else ""
    L.append(f"Xswp VINP topp trk trkb{pclk} VDDA VSS tgsw"); L.append(f"Xswn VINN topn trk trkb{pclk} VDDA VSS tgsw")
    L.append("Xcmp ck topp topn oa ob VDDA VSS comp")
    # --- DAC capacitors
    def capline(name, t, b, n):
        if flat_units:
            return [f"X{name}_{u} {t} {b} sky130_fd_pr__cap_mim_m3_1 W={CU_W:g} L={CU_L:g} MF=1" for u in range(n)]
        return [f"X{name} {t} {b} sky130_fd_pr__cap_mim_m3_1 W={CU_W:g} L={CU_L:g} MF=1 m={n}"]
    for k in range(10):
        L += capline(f"cp{k}", "topp", f"botp{k}", 2**k)
        L += capline(f"cn{k}", "topn", f"botn{k}", 2**k)
    L += capline("cpd", "topp", "VSS", 1); L += capline("cnd", "topn", "VSS", 1)
    # --- bottom drivers + state flops, 11 slices
    # NOR3 detectors. det_one_input grounds B/C to reduce latch loading and
    # eliminate the extracted high-CM alternating-decision band; dly1 is retained.
    if prm("det_vdda", 0):   #  detectors placed inside the symmetric comparator block, powered from VDDA
        L.append(scr("nor3_1","nda", PINS["nor3_1"], dict(A="oa", B="VSS" if prm("det_one_input",0) else "oa", C="VSS" if prm("det_one_input",0) else "oa", Y="ia_d"), vp="VDDA"))
        L.append(scr("nor3_1","ndb", PINS["nor3_1"], dict(A="ob", B="VSS" if prm("det_one_input",0) else "ob", C="VSS" if prm("det_one_input",0) else "ob", Y="ib_d"), vp="VDDA"))
    else:
        L.append(cellx("nor3_1","nda", A="oa", B="oa", C="oa", Y="ia_d"))   # ia_d = 1 when inp>inn  (oa falls)
        L.append(cellx("nor3_1","ndb", A="ob", B="ob", C="ob", Y="ib_d"))   # ib_d = 1 when inp<inn
    L.append(cellx("buf_2","bia", A="ia_d", X="ia")); L.append(cellx("buf_2","bib", A="ib_d", X="ib"))
    L.append(cellx("or2_1","orv", A="ia_d", B="ib_d", X="valid"))
    capture_cells = prm("dly1_cells", [prm("dly1","dlygate4sd3_1")] * prm("dly1_n",1))
    assert len(capture_cells) == prm("dly1_n",1)
    for j in range(prm("dly1_n",1)):
        L.append(cellx(capture_cells[j],f"dly_cap{j}", A=("valid" if j==0 else f"vcap_{j-1}"), X=(("vcap_raw" if prm("vcap_buf",0) else "vcap") if j==prm("dly1_n",1)-1 else f"vcap_{j}")))
    if prm("vcap_buf",0): L.append(cellx("buf_8","buf_vcap", A="vcap_raw", X="vcap"))
    for j in range(prm("dly2_n",1)):
        L.append(cellx(prm("dly2","dlygate4sd3_1"),f"dly_vd{j}", A=("vcap" if j==0 else f"vd2_{j-1}"), X=f"vd2_{j}"))
    vd2 = f"vd2_{prm('dly2_n',1)-1}"
    if prm("early_wait_stages",0):
        for j in range(prm("early_wait_stages",0)):
            L.append(cellx("dlygate4sd3_1",f"signoff_wait{j}", A="vcap" if j==0 else f"signoff_wait{j-1}", X=f"signoff_wait{j}"))
        L.append(cellx("and2b_1","signoff_hold", A_N="q3", B=f"signoff_wait{prm('early_wait_stages',0)-1}", X="signoff_hold"))
        L.append(cellx("or2_1","signoff_or", A=vd2, B="signoff_hold", X="signoff_vdck"))
        vd2="signoff_vdck"
    L.append(cellx("nor3_1","nor_ck", A=vd2, B="clkd", C="q11", Y="ck_raw"))
    L.append(cellx("buf_4","buf_ck", A="ck_raw", X="ck"))
    # clock conditioning
    if prm("sw_bigdrv", 0):   # strong clock drivers: fast, level-independent TG turn-off
        L.append(cellx("and2_4","buf_trk0", A="CLK", B="clkd", X="trk0") if prm("late_track",0) else cellx("buf_4","buf_trk0", A="CLK", X="trk0")); 
        for j in range(prm("clock_mult",1)):
            L.append(cellx("clkbuf_16", "buf_trk" if j==0 else f"buf_trk_{j}", A="trk0", X="trk"))
            L.append(cellx("inv_16", "inv_trkb" if j==0 else f"inv_trkb_{j}", A="trk", Y="trkb"))
    else:
        L.append(cellx("buf_2","buf_trk", A="CLK", X="trk")); L.append(cellx("inv_2","inv_trkb", A="trk", Y="trkb"))
    if prm("sw_dummy_p_inv",0): L.append(cellx("inv_8","inv_pdmy", A="trkb", Y="dummy_ptrk"))
    for j in range(prm("dlyclk_n",2)):
        L.append(cellx(prm("dlyclk","dlygate4sd3_1"),f"dly_clk{j}", A=("CLK" if j==0 else f"clkd_{j-1}"), X=f"clkd_{j}"))
    L.append(cellx("buf_2","buf_clkd", A=f"clkd_{prm('dlyclk_n',2)-1}", X="clkd"))
    L.append(cellx(prm("rst_drv","inv_1"),"inv_rstb", A="CLK" if prm("early_reset",0) else "clkd", Y="rstb")); L.append(cellx("inv_1","inv_run", A="clkd", Y="run"))
    # token (thermometer) chain: q0 = run ; q_i set at falling edge of vcap during step i
    for i in range(1, 12):
        qprev = "run" if i == 1 else f"q{i-1}"
        if prm("token_gate",0):
            L.append(cellx("and2b_1",f"tken{i}", A_N=f"q{i}", B=qprev, X=f"ten{i}"))
            L.append(cellx("dlclkp_1",f"tkcg{i}", CLK="vcap", GATE=f"ten{i}", GCLK=f"tclk{i}"))
        L.append(cellx("dfrtn_1", f"fq{i}", CLK_N=f"tclk{i}" if prm("token_gate",0) else "vcap", D=qprev, RESET_B="rstb", Q=f"q{i}"))
    for i in range(1, 12):
        k = 10 - i
        L.append(cellx("and3b_1", f"g{i}", A_N=f"q{i}", B=("run" if i == 1 else f"q{i-1}"), C="vcap", X=f"gck{i}"))
        L.append(cellx("dfrtp_1", f"fn{i}", CLK=f"gck{i}", D="ia", RESET_B="rstb", Q=f"n{i}"))
        if i <= 10:
            L.append(cellx("dfrtp_1", f"fp{i}", CLK=f"gck{i}", D="ib", RESET_B="rstb", Q=f"p{i}"))
            first, wp, wn = driver_sizes(k)
            for s, st in (("p", f"p{i}"), ("n", f"n{i}")):
                L.append(cellx(first, f"i1{s}{i}", A=st, Y=f"{s}b{i}"))
                for q, cellname in enumerate(DRV[k]):
                    L.append(scr(cellname, f"dr{s}{i}_{q}", PINS[cellname], dict(A=f"{s}b{i}", Y=f"bot{s}{k}"), vp="VREFP"))
        L.append(cellx("buf_2", f"ob{i}", A=f"n{i}", X=f"D{11-i}"))
    L.append(cellx("buf_2","obdv", A="q11", X="DV"))
    if flat_units:
        for side in ("p", "n"):
            for j in range(132): L.append(f"Xring{side}{j} VSS VSS sky130_fd_pr__cap_mim_m3_1 W={CU_W:g} L={CU_L:g} MF=1")
    L.append(".ends sar_adc")
    return "\n".join(L)
if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "sar_adc_m3.spice"), "w").write(build(False) + "\n")
    open(os.path.join(OUT, "sar_adc_m3_units.spice"), "w").write(build(True) + "\n")
    print("wrote", OUT)
